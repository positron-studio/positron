// The station's driver is workers/cast/container/live.mjs itself, rewritten only where an object differs: its
// imports point at the station's chain (station-grains.mjs) and source (source.mjs) and at demo/'s shared modules,
// its timers run on audio time (vclock.mjs), and a load is refused. Run before wrangler: node workers/edgecast/gen-live.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../cast/container/live.mjs', import.meta.url), 'utf8');
const swaps = [
  ["import { startGrains, MASTER_NODE } from './grains.mjs';", "import { startGrains, MASTER_NODE } from './station-grains.mjs';\nimport { T } from './vclock.mjs';"],
  ["from './sc/radio/cast/master.mjs';", "from '../../demo/radio/cast/master.mjs';"],
  ["import { openDecoder } from './decode.mjs';", "import { openDecoder } from './source.mjs';"],
  ["from './mixer.mjs';", "from '../cast/container/mixer.mjs';"],
  ["from './sc/radio/cast/life.mjs';", "from '../../demo/radio/cast/life.mjs';"],
  ["import { prepareLoad } from './load.mjs';", "const prepareLoad = async () => ({ ok: false, why: 'edgecast takes no load' });"],
  ["from './sc/radio/cast/layers.mjs';", "from '../../demo/radio/cast/layers.mjs';"],
  ["from './sc/radio/cast/soften.mjs';", "from '../../demo/radio/cast/soften.mjs';"],
  ['engine: e, heard: g.heard, set: g.set,', '__g: g, engine: e, heard: g.heard, set: g.set,'],
  ['const r = Math.sqrt(s2 / ONSET_N), now = Date.now();', 'const r = Math.sqrt(s2 / ONSET_N), now = T.now();'],
];
let out = src;
for (const [a, b] of swaps) {
  if (!out.includes(a)) throw new Error(`live.mjs no longer has: ${a}`);
  out = out.split(a).join(b);
}
let timers = 0;
out = out.replace(/(?<![.\w])(setTimeout|clearTimeout|setInterval|clearInterval)\(/g, (m, f) => { timers++; return `T.${f}(`; });
if (/from '\.\/(?!station-grains|vclock|source)/.test(out)) throw new Error('an import of live.mjs was not rewritten');
writeFileSync(new URL('./live.gen.mjs', import.meta.url), `// generated by gen-live.mjs from workers/cast/container/live.mjs; do not edit\n${out}`);
console.log(`live.gen.mjs: ${out.length} chars, ${timers} timer calls on audio time`);
